// Builds the chosen palette: semantic light/dark tokens plus 50-900 scales, and checks contrast.
// Usage: node build-final.mjs <presetId>   -> writes final-palette.json and final-palette.css
import { readFileSync, writeFileSync } from 'node:fs';

const dir = new URL('.', import.meta.url);
globalThis.window = {};
for (const f of ['color.js', 'theme.js', 'presets.js']) (0, eval)(readFileSync(new URL(f, dir), 'utf8'));
const { oklch, contrast } = window.Color;

const id = process.argv[2] || 'cobalt';
const preset = window.PRESETS.find((p) => p.id === id);
if (!preset) throw new Error(`unknown preset: ${id}`);
const theme = window.buildTheme(preset);

// Lightness steps chosen so 500 sits near the preset's brand lightness and 50/900 stay usable as tint/ink.
const STEPS = { 50: 0.97, 100: 0.93, 200: 0.87, 300: 0.78, 400: 0.66, 500: 0.56, 600: 0.47, 700: 0.4, 800: 0.33, 900: 0.26 };
// Chroma tapers at both ends so tints don't look neon and dark shades don't go muddy.
const taper = (L) => Math.max(0.25, 1 - Math.abs(L - 0.52) * 1.4);
const scale = (C, h) => Object.fromEntries(Object.entries(STEPS).map(([k, L]) => [k, oklch(L, C * taper(L), h)]));
const NEUTRAL = { 0: 1, 50: 0.985, 100: 0.96, 200: 0.92, 300: 0.86, 400: 0.71, 500: 0.56, 600: 0.45, 700: 0.37, 800: 0.27, 900: 0.21, 950: 0.165 };

const out = {
  preset: preset.id,
  params: Object.fromEntries(Object.entries(preset).filter(([k]) => /^(brand|accent|neutral)/.test(k))),
  primary: scale(preset.brandC, preset.brandH),
  accent: scale(Math.max(preset.accentC, 0.06), preset.accentH),
  neutral: Object.fromEntries(Object.entries(NEUTRAL).map(([k, L]) => [k, oklch(L, preset.neutralC, preset.neutralH)])),
  light: theme.light,
  dark: theme.dark,
};

const PAIRS = [['text', 'bg', 4.5], ['muted', 'surfaceAlt', 4.5], ['onPrimary', 'primary', 4.5], ['onAccent', 'accent', 4.5],
  ['link', 'surface', 4.5], ['accentText', 'surface', 4.5], ['primary', 'surface', 3],
  ['success', 'surface', 4.5], ['warning', 'surface', 4.5], ['danger', 'surface', 4.5]];
let failed = 0;
for (const m of ['light', 'dark']) for (const [a, b, min] of PAIRS) {
  const r = contrast(out[m][a], out[m][b]);
  if (r < min) failed++;
  console.log(`${m.padEnd(5)} ${(a + '/' + b).padEnd(22)} ${r.toFixed(2).padStart(5)} ${r >= min ? 'ok' : 'FAIL'}`);
}
// White text on scale steps tells which shades can carry button labels.
console.log('white text ok on primary:', Object.entries(out.primary).filter(([, v]) => contrast('#FFFFFF', v) >= 4.5).map(([k]) => k).join(','));

const NAMES = { bg: 'color-bg', surface: 'color-surface', surfaceAlt: 'color-surface-alt', text: 'color-text', muted: 'color-text-secondary',
  border: 'color-border', primary: 'color-primary', primaryHover: 'color-primary-dark', onPrimary: 'color-on-primary', link: 'color-link',
  accent: 'color-accent', accentHover: 'color-accent-hover', onAccent: 'color-on-accent', accentText: 'color-accent-text',
  success: 'color-success', warning: 'color-warning', danger: 'color-danger' };
const ramp = (name, s) => Object.entries(s).map(([k, v]) => `  --${name}-${k}: ${v};`).join('\n');
const sem = (t) => Object.entries(NAMES).map(([k, n]) => `  --${n}: ${t[k]};`).join('\n');
const css = `/* Generated by build-final.mjs from preset "${preset.id}" */
:root {
${ramp('primary', out.primary)}
${ramp('accent', out.accent)}
${ramp('neutral', out.neutral)}

${sem(out.light)}
}

[data-theme='dark'] {
${sem(out.dark)}
}
`;
writeFileSync(new URL('final-palette.json', dir), JSON.stringify(out, null, 2) + '\n');
writeFileSync(new URL('final-palette.css', dir), css);
console.log(failed ? `${failed} pair(s) FAIL` : 'all pairs pass', '-> final-palette.json, final-palette.css');
process.exitCode = failed ? 1 : 0;
